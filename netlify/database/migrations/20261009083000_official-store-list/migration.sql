  linked := EXISTS(SELECT 1 FROM learners l WHERE l.store_id=item.id)
   OR EXISTS(SELECT 1 FROM reporting_access r WHERE r.site_id=item.id)
   OR EXISTS(SELECT 1 FROM store_managers m WHERE m.store_id=item.id)
   OR EXISTS(SELECT 1 FROM legacy_completions h WHERE h.store_id=item.id)
   OR EXISTS(SELECT 1 FROM certificates h WHERE h.store_id=item.id)
   OR EXISTS(SELECT 1 FROM assignment_history h WHERE h.store_id=item.id)
   OR EXISTS(SELECT 1 FROM credit_ledger h WHERE h.store_id=item.id AND h.kind NOT IN ('opening','period_topup'))
   OR EXISTS(SELECT 1 FROM courses c WHERE jsonb_exists(c.audience_json::jsonb->'sites',item.id))
   OR EXISTS(SELECT 1 FROM organisation_stores s WHERE s.id=item.id AND (s.admin_learner_id IS NOT NULL OR s.store_code IS NOT NULL));
  INSERT INTO organisation_store_import_history(batch_id,store_id,decision,before_store,before_credit_account)
   VALUES('official-2026-10-09',item.id,CASE WHEN linked THEN 'retained for review' ELSE 'archived unused legacy' END,before_row,before_account);
  INSERT INTO organisation_stores(id,name,country,active,updated_by,updated_at)
   VALUES(item.id,item.name,item.country,linked,'official store import 2026-10-09',now()::text)
   ON CONFLICT(id) DO UPDATE SET active=CASE WHEN linked THEN organisation_stores.active ELSE false END,
    updated_by=excluded.updated_by,updated_at=excluded.updated_at;
  UPDATE store_credit_accounts a SET active=s.active FROM organisation_stores s WHERE s.id=item.id AND a.store_id=s.id;
  INSERT INTO organisation_store_audit(id,store_id,actor,action,recorded_at)
   VALUES(gen_random_uuid()::text,item.id,'official store import 2026-10-09',CASE WHEN linked THEN 'retain for review' ELSE 'archive unused legacy' END,now()::text);
